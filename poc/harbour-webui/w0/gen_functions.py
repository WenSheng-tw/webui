#!/usr/bin/env python3
"""Validate functions.txt against include/webui.h and generate bridge_request.prg.

  gen_functions.py                  check only (TAP output, exit 1 on failure)
  gen_functions.py --request FILE   check, then write the REQUEST lines for the
                                    in-scope functions to FILE ('-' = stdout)
  gen_functions.py --request FILE --upto W1   REQUEST lines of the waves W1..W1 only
  gen_functions.py --names WAVE     print the C names of one wave (W1..W5, EXCLUDED, ALL)

HB_FUN names are the C name upper-cased: webui_new_window -> WEBUI_NEW_WINDOW.
"""

import argparse
import collections
import sys

import hdrparse

EXPECTED = collections.OrderedDict(
    [("W1", 12), ("W2", 29), ("W3", 27), ("W4", 25), ("W5", 11), ("EXCLUDED", 8)]
)
IN_SCOPE_TOTAL = 104
HEADER_TOTAL = 112

SPEC_EXCLUDED = frozenset(
    """webui_malloc webui_memcpy
    webui_set_logger webui_set_close_handler_wv webui_set_file_handler
    webui_set_file_handler_window webui_return_http
    webui_interface_set_response_file_handler""".split()
)
SPEC_W1 = frozenset(
    """webui_new_window webui_bind webui_show webui_wait webui_wait_async
    webui_close webui_exit webui_clean webui_set_timeout webui_set_config
    webui_get_string webui_return_string""".split()
)


class Tap(object):
    def __init__(self):
        self.n = 0
        self.failed = 0
        self.lines = []

    def ok(self, cond, desc, diag=None):
        self.n += 1
        if not cond:
            self.failed += 1
        self.lines.append("%s %d - %s" % ("ok" if cond else "not ok", self.n, desc))
        if not cond and diag:
            for d in diag:
                self.lines.append("# " + d)


def check():
    tap = Tap()
    hdr = [p[0] for p, _ in hdrparse.header_protos()]
    rows = hdrparse.read_functions()
    names = [r[0] for r in rows]

    tap.ok(len(hdr) == HEADER_TOTAL, "header declares %d functions (got %d)" % (HEADER_TOTAL, len(hdr)))
    tap.ok(len(set(hdr)) == len(hdr), "header function names are unique")

    cnt = collections.Counter(names)
    dups = sorted(n for n, c in cnt.items() if c > 1)
    tap.ok(not dups, "no function listed twice", ["duplicate: " + d for d in dups])
    missing = sorted(set(hdr) - set(names))
    tap.ok(not missing, "every header function is listed", ["missing: " + m for m in missing])
    extra = sorted(set(names) - set(hdr))
    tap.ok(not extra, "no listed function is absent from the header", ["extra: " + e for e in extra])
    tap.ok(len(names) == HEADER_TOTAL, "list has %d rows (got %d)" % (HEADER_TOTAL, len(names)))

    waves = collections.Counter(r[1] for r in rows)
    unknown = sorted(set(waves) - set(EXPECTED))
    tap.ok(not unknown, "only known wave labels used", ["unknown label: " + u for u in unknown])
    for w, want in EXPECTED.items():
        tap.ok(waves.get(w, 0) == want, "%s has %d functions (got %d)" % (w, want, waves.get(w, 0)))
    in_scope = sum(c for w, c in waves.items() if w != "EXCLUDED")
    tap.ok(in_scope == IN_SCOPE_TOTAL, "in-scope waves sum to %d (got %d)" % (IN_SCOPE_TOTAL, in_scope))

    excl = frozenset(r[0] for r in rows if r[1] == "EXCLUDED")
    tap.ok(excl == SPEC_EXCLUDED, "EXCLUDED set equals the 8 names (spec section 1 minus set_context and get_context, CEO decision)",
           ["unexpected: %s" % sorted(excl - SPEC_EXCLUDED), "absent: %s" % sorted(SPEC_EXCLUDED - excl)])
    w1 = frozenset(r[0] for r in rows if r[1] == "W1")
    tap.ok(w1 == SPEC_W1, "W1 set equals the 12 names of spec section 7",
           ["unexpected: %s" % sorted(w1 - SPEC_W1), "absent: %s" % sorted(SPEC_W1 - w1)])
    hw = {r[0]: r[1] for r in rows if "hwnd" in r[0]}
    ctx = {r[0]: r[1] for r in rows if r[0].endswith("_context")}
    tap.ok(ctx == {"webui_set_context": "W2", "webui_get_context": "W2"}, "set_context and get_context are W2 (CEO decision)")
    tap.ok(hw == {"webui_get_hwnd": "W4", "webui_win32_get_hwnd": "W4"}, "get_hwnd functions are W4 (spec rev 1)")
    tap.ok(names == hdr, "list order follows the header order")
    return tap, rows


def hb_name(c_name):
    return c_name.upper()


def write_request(rows, dest, upto=None):
    waves = list(EXPECTED)[:-1]
    if upto:
        waves = waves[:waves.index(upto) + 1]
    in_scope = [r for r in rows if r[1] in waves]
    out = [
        "/*",
        " * bridge_request.prg  --  GENERATED by w0/gen_functions.py from w0/functions.txt",
        " * Do not edit. Forces every in-scope WEBUI_* symbol into the exe symbol table so",
        " * that .hrb files loaded with hb_hrbLoad() can resolve them (spec 8.3).",
        " * %d functions (%s)." % (len(in_scope), ", ".join("%s %d" % (w, sum(1 for r in in_scope if r[1] == w)) for w in waves)),
        " */",
        "",
    ]
    for wave in waves:
        out.append("/* %s */" % wave)
        for name, w, _ in in_scope:
            if w == wave:
                out.append("REQUEST %s" % hb_name(name))
        out.append("")
    # A module that only holds REQUEST lines compiles to nothing ("Empty source file"), so
    # the symbols would never reach the exe symbol table. A procedure makes it a real module.
    out += ["PROCEDURE BridgeRequestAnchor()", "RETURN", ""]
    text = "\n".join(out)
    if dest == "-":
        sys.stdout.write(text)
    else:
        with open(dest, "w") as f:
            f.write(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--request", metavar="FILE")
    ap.add_argument("--names", metavar="WAVE")
    ap.add_argument("--upto", metavar="WAVE", help="with --request: only waves W1..WAVE")
    args = ap.parse_args()

    tap, rows = check()
    if args.names:
        sel = [r[0] for r in rows if args.names == "ALL" or r[1] == args.names]
        sys.stdout.write("\n".join(sel) + "\n")
        return 0 if not tap.failed else 1
    report = sys.stderr if args.request == "-" else sys.stdout
    report.write("TAP version 13\n1..%d\n%s\n" % (tap.n, "\n".join(tap.lines)))
    if tap.failed:
        report.write("# FAILED %d of %d checks\n" % (tap.failed, tap.n))
        return 1
    if args.request:
        write_request(rows, args.request, args.upto)
    return 0


if __name__ == "__main__":
    sys.exit(main())
